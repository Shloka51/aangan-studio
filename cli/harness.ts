// Text harness: feed a transcript in, print outcome + handoff note + actions.
//   npm run harness -- T02            one labelled transcript
//   npm run harness -- --all          all T01–T20 with pass/fail vs label
//   npm run harness -- --file x.json  an Enquiry JSON ({ caller, receivedAt, status, turns })
//   add --live to use Gemini (needs GEMINI_API_KEY)
import "@/cli/env";
import { readFileSync } from "node:fs";
import { calcomLink } from "@/adapters/booking/calcom";
import { createBrain } from "@/adapters/brain";
import { processEnquiry } from "@/core/session";
import type { Enquiry, EnquiryResult } from "@/core/types";
import { loadFixtures, toEnquiry } from "@/tests/support/fixtures";

const args = process.argv.slice(2);
const live = args.includes("--live");
const C = { dim: "\x1b[2m", bold: "\x1b[1m", green: "\x1b[32m", red: "\x1b[31m", yellow: "\x1b[33m", cyan: "\x1b[36m", reset: "\x1b[0m" };

async function run(e: Enquiry): Promise<EnquiryResult> {
  const brain = await createBrain({ live });
  return processEnquiry(e, { brain, bookingLink: calcomLink, clock: () => new Date(e.receivedAt) });
}

function print(r: EnquiryResult) {
  console.log(`\n${C.bold}${r.enquiry.id}${C.reset}  ${C.dim}${r.enquiry.receivedAt}${r.afterHours ? " (after hours)" : ""}${C.reset}`);
  console.log(`${C.cyan}— Conversation (agent turns generated by the core) —${C.reset}`);
  for (const t of r.transcript) console.log(t.speaker === "agent" ? `  ${C.green}Agent${C.reset} [${t.action}]${t.guardrail ? ` ${C.red}[guardrail]${C.reset}` : ""}: ${t.text}` : `  ${C.yellow}Caller${C.reset}: ${t.text}`);
  console.log(`${C.cyan}— Qualification —${C.reset}`);
  for (const c of r.qualification.criteria) console.log(`  ${c.status === "PASS" ? C.green : c.status === "FAIL" ? C.red : C.yellow}${c.status.padEnd(9)}${C.reset} ${c.id}. ${c.name}: ${c.reason}`);
  console.log(`${C.cyan}— Outcome —${C.reset}\n  ${C.bold}${r.outcome.kind}${C.reset}${r.outcome.declineReason ? ` (${r.outcome.declineReason})` : ""}${r.outcome.recovery ? " [RECOVERY]" : ""}\n  Next step: ${r.outcome.nextStep}`);
  console.log(`${C.cyan}— Actions —${C.reset}`);
  for (const a of r.actions) {
    if (a.type === "send_handoff") console.log(`  send_handoff →\n${a.text.split("\n").map((l) => "    │ " + l).join("\n")}`);
    else console.log(`  ${a.type} ${JSON.stringify({ ...a, type: undefined })}`);
  }
  if (r.guardrailEvents.length) console.log(`${C.red}— Guardrail rewrites: ${r.guardrailEvents.length} —${C.reset}`);
  if (r.usage.length) console.log(`${C.dim}Cost: ₹${r.usage.reduce((s, u) => s + u.costInr, 0).toFixed(3)} over ${r.usage.length} model calls${C.reset}`);
}

async function main() {
  const fileIdx = args.indexOf("--file");
  if (fileIdx >= 0) {
    const e = JSON.parse(readFileSync(args[fileIdx + 1], "utf8"));
    print(await run({ id: "file", channel: "phone", status: "answered", receivedAt: new Date().toISOString(), turns: [], caller: {}, ...e }));
    return;
  }
  const fixtures = loadFixtures();
  const ids = args.filter((a) => /^T\d/.test(a));
  const selected = args.includes("--all") || !ids.length ? fixtures : fixtures.filter((f) => ids.some((id) => f.id.startsWith(id)));
  let pass = 0;
  for (const f of selected) {
    const r = await run(toEnquiry(f));
    if (selected.length === 1 || !args.includes("--all")) print(r);
    const ok = r.outcome.kind === f.expected.outcome && (!f.expected.declineReason || r.outcome.declineReason === f.expected.declineReason);
    if (ok) pass++;
    if (args.includes("--all"))
      console.log(`${ok ? C.green + "PASS" : C.red + "FAIL"}${C.reset} ${f.id.padEnd(5)} expected ${f.expected.outcome}${f.expected.declineReason ? `/${f.expected.declineReason}` : ""} → got ${r.outcome.kind}${r.outcome.declineReason ? `/${r.outcome.declineReason}` : ""}${r.outcome.recovery ? " [recovery]" : ""}`);
  }
  if (args.includes("--all")) console.log(`\n${pass}/${selected.length} match their labels`);
}

main();
