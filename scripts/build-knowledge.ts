// Embeds /knowledge/*.md into core/knowledge/generated.ts so the core runs the
// same way in the CLI, in tests and inside a Vercel serverless bundle.
// /knowledge stays the source of truth: tests fail if this file is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const files = { SERVICES_MD: "services.md", QUALIFIED_MD: "qualified.md", PRICING_MD: "pricing.md" };

let out = "// GENERATED by scripts/build-knowledge.ts from /knowledge. Do not edit.\n";
out += "// PRICING_MD is internal: it feeds the guardrail blocklist and budget sanity\n";
out += "// check only. It is never placed in a model prompt or a caller-facing reply.\n\n";
for (const [name, file] of Object.entries(files)) {
  out += `export const ${name} = ${JSON.stringify(readFileSync(join(root, "knowledge", file), "utf8"))};\n\n`;
}
writeFileSync(join(root, "core/knowledge/generated.ts"), out);
console.log("knowledge embedded");
